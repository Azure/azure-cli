"""Azure CLI pre-publication checks run by the engine before a change is published."""

import ast
import os
import re

import yaml

from repository_tools.reviewer.policy import analysis
from repository_tools.settings import AAZ_FIX_ROUTE, AAZ_SOURCE_REPOSITORY, _AAZ_OUTPUT_PATTERN

_AAZ_HEADER = re.compile(r"^#\s*Code generated by aaz-dev-tools\b", re.I | re.M)
_SETUP_VERSION = re.compile(r"^\s*VERSION\s*=", re.M)
_EXTENSION_SETUP = re.compile(r"src/[^/]+/setup\.py")
_VENDORED_SDK = (
    re.compile(r"(?:^|/)vendored_sdks?/.*(?:_client|_configuration|_serialization)\.py$", re.I),
    re.compile(r"(?:^|/)vendored_sdks?/.*/models/_models.*\.py$", re.I),
)
_CLI_COMMAND_METHODS = {
    "command", "custom_command", "show_command", "custom_show_command",
    "wait_command", "custom_wait_command", "generic_update_command",
    "generic_wait_command",
}
_PARAM_HELP_EXEMPT = {
    "resource_group_name", "location", "tags", "no_wait", "ids",
    "subscription", "yes", "cmd",
}


def finding(summary, remediation, path=None, line=None):
    item = {"summary": summary, "remediation": remediation}
    if path:
        item["file"] = path
    if line is not None:
        item["line"] = line
    return item


def added_lines(change):
    return list(analysis._review_added_lines(change))


def generated_paths(paths):
    """Vendored generated SDK files the engine's common patterns do not recognise."""
    return {
        path: {"kind": "other_generated", "reason": "generated file", "checked": False}
        for path in paths if any(pattern.search(path) for pattern in _VENDORED_SDK)
    }


def production_changes(repository, changes):
    return [change for change in changes if analysis._review_is_production_file(repository, change["filename"])]


def extension_release_findings(changes, production):
    findings = []
    by_path = {change["filename"]: change for change in changes}
    if "src/index.json" in by_path:
        findings.append(finding(
            "`src/index.json` is maintained by the extension release pipeline.",
            "Revert the `src/index.json` edit; release automation updates it after publishing.",
            "src/index.json",
        ))
    components = sorted({
        change["filename"].split("/")[1] for change in production
        if change["filename"].startswith("src/") and change["filename"].count("/") >= 2
        and analysis._review_has_customer_visible_change(change)
    })
    for component in components:
        setup = by_path.get(f"src/{component}/setup.py")
        if setup is None or not any(_SETUP_VERSION.match(text) for _, text in added_lines(setup)):
            findings.append(finding(
                f"Customer-visible change to extension `{component}` without a `VERSION` bump in its setup.py.",
                f"Bump `VERSION` in `src/{component}/setup.py` (patch for fixes, minor for features).",
                f"src/{component}/setup.py",
            ))
    return findings


def _wire(items):
    return [
        finding(item["summary"], item["remediation"], item.get("file"), item.get("line"))
        for item in items or []
    ]


def release_artifact_findings(repository, target_kind, pr, changes):
    """Release artifact findings: the shared review check plus extension version rules."""
    production = production_changes(repository, changes)
    items, _ = analysis._release_artifact_check(repository, pr, changes, production, None, None)
    findings = _wire(items)
    if target_kind == "extension":
        findings += extension_release_findings(changes, production)
    return findings


def generated_ownership_findings(repository, pr, changes):
    production = production_changes(repository, changes)
    items, _ = analysis._generated_ownership_check(
        repository, pr, changes, production, None, None, generation_source_prs=[],
    )
    return _wire(items)


def checklist_statuses(changed):
    return {
        "extension-version": (
            "passed" if any(_EXTENSION_SETUP.fullmatch(path) for path in changed)
            else "not applicable"
        ),
    }


def generated_output_findings(pr, changes, base, head):
    """AAZ output is allowed only when regenerated alongside an AAZ model change."""
    aaz = [change for change in changes if _AAZ_OUTPUT_PATTERN.search(change["filename"])]
    if not aaz:
        return []
    paired = bool(pr.get("generation_source_pr_url")) or (
        pr.get("generation_source_repository") == AAZ_SOURCE_REPOSITORY
    )
    findings = []
    for change in aaz:
        path = change["filename"]
        old, new = base.get(path), head.get(path)
        if not paired:
            findings.append(finding(
                "Hand edit of AAZ generated command output without a matching "
                "Azure/aaz command-model change.", AAZ_FIX_ROUTE, path,
            ))
        elif new is not None and not _AAZ_HEADER.search(new[:2000]) and (
            old is None or _AAZ_HEADER.search(old[:2000])
        ):
            findings.append(finding(
                "AAZ file lacks the `Code generated by aaz-dev-tools` header that "
                "aaz-dev regeneration writes, so it was not regenerated.",
                AAZ_FIX_ROUTE, path,
            ))
    return findings


def _string(node):
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def _parse(text):
    try:
        return ast.parse(text or "")
    except (SyntaxError, ValueError):
        return None


def _help_entries(tree):
    """helps['name'] = '''yaml''' assignments as {name: (yaml, first, last)}."""
    entries = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if (
            isinstance(target, ast.Subscript) and isinstance(target.value, ast.Name)
            and target.value.id == "helps"
        ):
            key = _string(target.slice)
            value = _string(node.value)
            if key is not None and value is not None:
                entries[key.strip()] = (value, node.lineno, node.end_lineno or node.lineno)
    return entries


def _help_entry_findings(path, text, changed_lines):
    tree = _parse(text)
    if tree is None:
        return []
    findings = []
    for key, (value, first, last) in _help_entries(tree).items():
        if not any(first <= number <= last for number in changed_lines):
            continue
        try:
            entry = yaml.safe_load(value)
        except yaml.YAMLError:
            findings.append(finding(
                f"Help entry `{key}` is not valid YAML.", "Fix the YAML in the help entry.", path, first,
            ))
            continue
        problems = []
        if not isinstance(entry, dict):
            problems.append("is not a mapping")
        else:
            if entry.get("type") not in {"command", "group"}:
                problems.append("needs `type: command` or `type: group`")
            if not str(entry.get("short-summary") or "").strip():
                problems.append("needs a `short-summary`")
            examples = entry.get("examples") or []
            if not isinstance(examples, list):
                problems.append("has malformed `examples`")
            else:
                for example in examples:
                    if (
                        not isinstance(example, dict)
                        or not str(example.get("name") or "").strip()
                        or not str(example.get("text") or "").strip().startswith("az ")
                    ):
                        problems.append("has an example without a `name` or an `az ...` `text`")
                        break
        if problems:
            findings.append(finding(
                f"Help entry `{key}` " + "; ".join(problems) + ".",
                "Follow the Azure CLI help style: type, short-summary and runnable `az` examples.",
                path, first,
            ))
    return findings


def _command_names(tree):
    names = set()
    if tree is None:
        return names
    for node in ast.walk(tree):
        if not isinstance(node, ast.With):
            continue
        for item in node.items:
            call = item.context_expr
            if not (
                isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute)
                and call.func.attr == "command_group" and call.args
                and isinstance(item.optional_vars, ast.Name)
            ):
                continue
            group, alias = _string(call.args[0]), item.optional_vars.id
            if group is None:
                continue
            for inner in ast.walk(node):
                if (
                    isinstance(inner, ast.Call) and isinstance(inner.func, ast.Attribute)
                    and isinstance(inner.func.value, ast.Name) and inner.func.value.id == alias
                    and inner.func.attr in _CLI_COMMAND_METHODS and inner.args
                ):
                    name = _string(inner.args[0])
                    if name:
                        names.add(" ".join(f"{group} {name}".split()))
    return names


def _new_command_findings(path, base_text, head_text, read_file):
    new = _command_names(_parse(head_text)) - _command_names(_parse(base_text))
    if not new:
        return []
    help_path = f"{os.path.dirname(path)}/_help.py"
    help_text = read_file(help_path)
    if help_text is None:
        return []
    tree = _parse(help_text)
    documented = set(_help_entries(tree)) if tree is not None else set()
    return [
        finding(
            f"New command `az {name}` has no `_help.py` entry.",
            f"Add a `helps['{name}']` entry with a short-summary and a runnable example.", help_path,
        )
        for name in sorted(new - documented)
    ]


def _argument_calls(tree):
    """c.argument('name', ...) calls as (name, line, has_help)."""
    calls = []
    if tree is None:
        return calls
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
            and node.func.attr == "argument" and isinstance(node.func.value, ast.Name)
            and node.args and _string(node.args[0])
        ):
            keywords = {keyword.arg for keyword in node.keywords}
            has_help = (
                len(node.args) > 1 or bool(keywords & {"help", "arg_type"}) or None in keywords
            )
            calls.append((_string(node.args[0]), node.lineno, has_help))
    return calls


def _parameter_help_findings(path, base_text, head_text):
    head = _argument_calls(_parse(head_text))
    base = {name for name, _, _ in _argument_calls(_parse(base_text))}
    documented = {name for name, _, has_help in head if has_help}
    findings = []
    for name, line, has_help in head:
        if has_help or name in base or name in documented or name in _PARAM_HELP_EXEMPT:
            continue
        findings.append(finding(
            f"New parameter `{name}` has no help text.",
            "Pass `help=` (or a documented `arg_type=`) for every new parameter.", path, line,
        ))
    return findings


def command_help_findings(changes, base, read_file):
    findings = []
    for change in changes:
        path = change["filename"]
        if not path.endswith(".py") or change["status"] == "removed" or analysis._review_is_test(path):
            continue
        head_text = read_file(path)
        if head_text is None:
            continue
        name = os.path.basename(path)
        if name == "_help.py":
            findings += _help_entry_findings(path, head_text, {number for number, _ in added_lines(change)})
        elif name == "commands.py":
            findings += _new_command_findings(path, base.get(path), head_text, read_file)
        elif name == "_params.py":
            findings += _parameter_help_findings(path, base.get(path), head_text)
    return findings


def title_findings(target_kind, title, prefix, rest, changed_paths):
    findings = []
    if prefix is None:
        findings.append(finding(
            "Azure CLI PR titles must start with `[Component]` (customer-facing) or `{Component}`.",
            "Prefix the title with the affected module's component name.",
        ))
    summary = re.sub(r"^Fix(?:es|ed)?\s+#\d+\s*:\s*", "", rest, flags=re.I)
    summary = re.sub(r"^`az\s[^`]*`\s*:\s*", "", summary).strip()
    if not summary or len(summary) < 4:
        findings.append(finding(
            "PR title has no customer-facing summary after the component/command.",
            "Describe the change after the `az <command>:` part.",
        ))
    elif not (summary[0].isupper() or summary[0] in "`#" or summary[0].isdigit()):
        findings.append(finding(
            "PR title summary must start with a capital letter.",
            "Capitalize the first word of the summary.",
        ))
    if target_kind == "module" and prefix is not None and changed_paths:
        from repository_tools.fixer.title_gate.title_repair import (
            cli_title_component_matches,
            expected_cli_title_component,
        )

        if not cli_title_component_matches(title, changed_paths):
            findings.append(finding(
                "PR title component does not match the changed module "
                f"(expected `{expected_cli_title_component(changed_paths)}`).",
                "Use the component of the single changed command module.",
            ))
    return findings
